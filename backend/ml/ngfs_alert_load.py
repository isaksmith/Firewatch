"""NGFS extra text load for March and April 2026 in four stand-in districts.

Run: PYTHONPATH=. .venv/bin/python -m ml.ngfs_alert_load   (writes ml/ngfs_alert_load.md)
Polite: one request per second, only the documented query URL, never a URL taken from a response.
Counts tracked features (feature_tracking_id) that would qualify under app.ngfs_signal.qualifying:
label "Possible Wildland Fire" and at least two separate acq_date_time values. The registered-burn
suppression cannot be replayed (no burn history), so counts are an upper bound on texts.
"""

import json
import time
import urllib.parse
import urllib.request
from collections import defaultdict
from pathlib import Path

from app.geo import haversine_km
from app.ngfs_signal import WILDLAND, qualifying

BASE = "https://fire.data.nesdis.noaa.gov/api/ogc/detections/collections/ngfs_schema.ngfs_detections_scene_east_conus/items"
DISTRICTS = {"Comanche": (37.19, -99.27), "Clark": (37.24, -99.82), "Barber": (37.23, -98.68), "Chase (Flint Hills)": (38.30, -96.59)}
RADIUS_KM = 19.3
START, END = "2026-03-01T00:00:00Z", "2026-05-01T00:00:00Z"


def fetch(lat, lon):
    d = RADIUS_KM / 111.0
    dl = d / max(0.2, abs(__import__("math").cos(__import__("math").radians(lat))))
    bbox = f"{lon - dl:.4f},{lat - d:.4f},{lon + dl:.4f},{lat + d:.4f}"
    rows, offset = [], 0
    while True:
        q = urllib.parse.urlencode({"f": "json", "limit": 1000, "bbox": bbox, "datetime": f"{START}/{END}",
                                    "sortby": "acq_date_time", "offset": offset})
        with urllib.request.urlopen(f"{BASE}?{q}", timeout=60) as r:
            feats = json.load(r)["features"]
        time.sleep(1)
        rows += feats
        if len(feats) < 1000:
            return rows
        offset += 1000


def point(f):
    g, p = f["geometry"], f["properties"]
    ring = g["coordinates"][0] if g["type"] == "Polygon" else g["coordinates"][0][0]
    lon = sum(c[0] for c in ring) / len(ring)
    lat = sum(c[1] for c in ring) / len(ring)
    return {"lat": lat, "lon": lon, "feature_tracking_id": p.get("feature_tracking_id"),
            "type_description": p.get("type_description"), "acq_date_time": p.get("acq_date_time")}


def main():
    lines = []
    for name, (lat, lon) in DISTRICTS.items():
        pts = [point(f) for f in fetch(lat, lon)]
        pts = [p for p in pts if haversine_km(lat, lon, p["lat"], p["lon"]) <= RADIUS_KM]
        nulls = sum(1 for p in pts if p["type_description"] in (None, ""))
        wild = [p for p in pts if p["type_description"] == WILDLAND]
        feats = {p["feature_tracking_id"] for p in pts if p["feature_tracking_id"] not in (None, "")}
        q = qualifying(pts)
        month = defaultdict(int)
        for x in q:
            month[x["last"][:7]] += 1
        lines.append((name, len(pts), nulls, len(wild), len(feats), len(q), month.get("2026-03", 0), month.get("2026-04", 0)))
    out = ["# NGFS extra text load, March and April 2026", "",
           "Generated by `backend/ml/ngfs_alert_load.py` from the NOAA NGFS GOES East CONUS collection. 12 mile (19.3 km) circles around the four stand-in district centers used in `alert_load.md`. Each row's footprint is reduced to its centroid.", "",
           "| District | Rows | Null type rows | Wildland rows | Tracked features | Qualifying features (extra Investigate texts) | March | April |", "|---|---|---|---|---|---|---|---|"]
    out += ["| " + " | ".join(str(x) for x in l) + " |" for l in lines]
    tot = [sum(l[i] for l in lines) for i in range(1, 8)]
    out.append("| All four | " + " | ".join(str(x) for x in tot) + " |")
    out += ["", "A feature qualifies if its type is `Possible Wildland Fire` and it has at least two separate scans. Null type rows are counted separately and never qualify. Registered-burn suppression cannot be replayed (no burn history), so these are upper bounds. Each qualifying feature is one FYI text to the duty officer at Investigate; NGFS alone never pages.", ""]
    Path(__file__).with_name("ngfs_alert_load.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
